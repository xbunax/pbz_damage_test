local Session=dofile(arg[1]..'/PBZTrainingDummy/Scripts/session.lua')
local s=Session.new()
Session.attach(s,'boss','arena')
assert(not Session.record(s,'boss',0,nil,1,0))
assert(not Session.record(s,'boss',0,nil,1,-10))
assert(not Session.record(s,'boss',0,nil,1,math.huge))
assert(not Session.record(s,'boss',0,nil,1,false))
assert(not Session.record(s,'other',0,nil,1,100))
assert(Session.record(s,'boss',0,nil,10,500),'A Shachi-only hit starts a measured run')
local snap=Session.snapshot(s,12)
assert(snap.events==1 and snap.total==0 and snap.shachiTotal==500)
assert(snap.dps==0 and snap.shachiDps==250 and snap.shachiRecentDps==100)
assert(snap.shachiMaximum==500 and snap.shachiLast==500)
assert(Session.record(s,'boss',100,nil,12))
assert(s.events==2 and s.last==100 and s.shachiLast==0)
assert(Session.record(s,'boss',50,nil,14,100))
assert(s.events==3 and s.total==150 and s.shachiTotal==600,'Mixed hit counts once, overkill is not clipped')
assert(Session.pause(s,15))
assert(not Session.record(s,'boss',999,nil,20,999))
local paused=Session.snapshot(s,100)
assert(paused.seconds==5 and paused.shachiDps==120 and paused.shachiRecentDps==20)
assert(Session.resume(s,25))
assert(Session.record(s,'boss',0,nil,27,300))
local continued=Session.snapshot(s,27)
assert(continued.seconds==7 and continued.shachiTotal==900 and continued.shachiRecentDps==80)
assert(continued.recentDps==10 and continued.events==4)
assert(not Session.record(s,'boss',0,nil,26,100),'Both channels reject time reversal')
assert(s.events==4 and s.shachiTotal==900)
Session.detach(s,28)
local frozen=Session.snapshot(s,1000)
assert(frozen.seconds==8 and frozen.shachiDps==112.5 and not frozen.active)
Session.attach(s,'next','arena')
assert(s.shachiTotal==0 and s.shachiMaximum==0 and s.shachiLast==0)
assert(Session.snapshot(s,1).shachiDps==0)
assert(Session.record(s,'next',0,nil,1,1e308))
assert(not Session.record(s,'next',0,nil,2,1e308),'Overflow must not corrupt the accumulated channel')
assert(s.events==1 and s.shachiTotal==1e308)
Session.reset(s)
assert(s.target=='next' and s.total==0 and s.shachiTotal==0 and #s.recent==0)
print('PASS: dual damage, Shachi-only timing, shared pauses, rolling windows, overkill, isolation and overflow')
