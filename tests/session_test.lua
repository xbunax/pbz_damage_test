local Session=dofile(arg[1]..'/PBZTrainingDummy/Scripts/session.lua')
local s=Session.new()
assert(not Session.record(s,'a',100,'physical',1))
Session.attach(s,'dummy','world')
assert(not Session.record(s,'other enemy',100,'physical',1))
assert(not Session.record(s,'dummy',0/0,'physical',1))
assert(not Session.record(s,'dummy',-50,'heal',1))
assert(Session.record(s,'dummy',500,'physical',1))
local hp,refill=Session.health_after(100,500,10000)
assert(hp==1 and refill)
assert(s.total==500) -- Overkill is not truncated to the 99 HP actually removed.
s.refills=s.refills+1
assert(Session.record(s,'dummy',70,'poison damage',1.01))
assert(s.total==570 and s.events==2) -- Refill does not reset the combo.
local h2,r2=Session.health_after(10000,70,10000)
assert(h2==9930 and not r2)
local h3,r3=Session.health_after(51,50,10000)
assert(h3==1 and r3)
assert(not Session.record(s,'dummy',20,'physical',0.5))
Session.reset(s)
assert(s.target=='dummy' and s.total==0 and s.refills==0)
Session.detach(s)
assert(not Session.record(s,'dummy',100,'physical',3))
Session.attach(s,'dummy2','world2')
assert(not Session.record(s,'dummy',100,'physical',4))
assert(Session.record(s,'dummy2',100,'physical',4))
assert(Session.snapshot(s,6).dps==50)
print('PASS: target isolation, overkill, lethal/exact-one floor, refill continuity, reset, stale events, DPS')
