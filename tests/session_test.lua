local Session=dofile(arg[1]..'/PBZTrainingDummy/Scripts/session.lua')
local s=Session.new()
assert(not Session.record(s,'a',100,'physical',1))
Session.attach(s,'dummy','world')
assert(not Session.record(s,'other enemy',100,'physical',1))
assert(not Session.record(s,'dummy',0/0,'physical',1))
assert(not Session.record(s,'dummy',-50,'heal',1))
assert(Session.record(s,'dummy',500,'physical',1))
local hp,refill=Session.health_after(100,500,10000)
assert(hp==1 and refill)
assert(s.total==500) -- Overkill is not truncated to the 99 HP actually removed.
s.refills=s.refills+1
assert(Session.record(s,'dummy',70,'poison damage',1.01))
assert(s.total==570 and s.events==2) -- Refill does not reset the combo.
local h2,r2=Session.health_after(10000,70,10000)
assert(h2==9930 and not r2)
local h3,r3=Session.health_after(51,50,10000)
assert(h3==1 and r3)
assert(not Session.record(s,'dummy',20,'physical',0.5))
Session.reset(s)
assert(s.target=='dummy' and s.total==0 and s.refills==0)
Session.detach(s)
assert(not Session.record(s,'dummy',100,'physical',3))
Session.attach(s,'dummy2','world2')
assert(not Session.record(s,'dummy',100,'physical',4))
assert(Session.record(s,'dummy2',100,'physical',4))
assert(Session.snapshot(s,6).dps==50)
assert(Session.snapshot(s,4).dps==100,'First-frame DPS uses a one-second minimum')
assert(Session.snapshot(s,6).recentDps==20)
assert(Session.record(s,'dummy2',200,'physical',8))
assert(Session.snapshot(s,8).recentDps==60)
assert(Session.snapshot(s,9).recentDps==40,'Window excludes its left boundary')
assert(Session.snapshot(s,13).recentDps==0,'Idle recent DPS becomes zero')
Session.detach(s,14)
local frozen=Session.snapshot(s,100)
assert(frozen.seconds==10 and frozen.dps==30 and not frozen.active)
Session.detach(s,200)
assert(Session.snapshot(s,300).dps==30,'Repeated removal must not restart or extend the clock')
Session.attach(s,'dummy3','world3')
assert(Session.snapshot(s,400).dps==0 and Session.snapshot(s,400).recentDps==0)
assert(#s.recent==0 and s.started==nil)
assert(Session.record(s,'dummy3',10,'physical',400))
assert(Session.record(s,'dummy3',20,'physical',406))
assert(#s.recent==1,'Old window hits are pruned even when menu stays closed')
Session.attach(s,'paused','world')
assert(Session.record(s,'paused',100,'physical',10))
assert(Session.pause(s,12))
assert(not Session.pause(s,13) and not Session.resume(s,11))
assert(not Session.record(s,'paused',999,'physical',50))
local frozenPause=Session.snapshot(s,100)
assert(frozenPause.seconds==2 and frozenPause.dps==50 and frozenPause.recentDps==20 and frozenPause.paused)
assert(s.events==1 and s.total==100 and #s.recent==1)
assert(Session.resume(s,102))
assert(Session.snapshot(s,104).seconds==4 and Session.snapshot(s,104).recentDps==20)
assert(Session.record(s,'paused',100,'physical',104))
assert(Session.snapshot(s,105).seconds==5 and Session.snapshot(s,105).recentDps==20)
assert(Session.pause(s,106) and Session.resume(s,116),'Multiple pauses are cumulative')
assert(Session.snapshot(s,117).seconds==7 and Session.snapshot(s,117).dps==200/7)
assert(Session.pause(s,118));Session.detach(s,200)
assert(Session.snapshot(s,999).seconds==8,'Removal while paused preserves measured duration')
Session.attach(s,'fresh','world');assert(Session.pause(s,250));assert(Session.resume(s,300))
assert(Session.snapshot(s,310).seconds==0,'Pausing before first hit does not start the timer')
assert(Session.record(s,'fresh',50,nil,310) and Session.snapshot(s,312).seconds==2)
Session.reset(s);assert(not s.paused and s.pausedTotal==0)
print('PASS: target isolation, overkill, refill/reset, DPS windows, repeated pause/resume and removal freezes')
